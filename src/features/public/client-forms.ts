export function clientFormBySlug(slug: string): ClientForm | undefined {
  return clientForms.find((f) => f.slug === slug);
}

/** Every input name in a form, in page order — used to build the summary. */
export function formFieldCount(form: ClientForm): number {
  let n = 0;
  for (const sec of form.sections) {
    for (const it of sec.items) {
      if (it.kind === "subhead") continue;
      n += it.kind === "checkboxes" ? it.options.length : 1;
    }
  }
  return n;
}
